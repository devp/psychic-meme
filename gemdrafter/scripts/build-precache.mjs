#!/usr/bin/env node
// Generate precache-manifest.js (url + content revision per app file), which
// sw.js loads via importScripts. --check fails if the committed file is stale.
//
//   node scripts/build-precache.mjs [--check]

import { getManifest } from "workbox-build";
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const check = process.argv.includes("--check");
const root = new URL("..", import.meta.url).pathname;
const out = join(root, "precache-manifest.js");

const { manifestEntries, warnings } = await getManifest({
  globDirectory: root,
  globPatterns: ["**/*.{html,css,js,webmanifest,svg}"],
  globIgnores: [
    "node_modules/**",
    "scripts/**",
    "tests/**",
    "sw.js",
    "precache-manifest.js",
  ],
});

const body =
  "// GENERATED by scripts/build-precache.mjs -- do not edit.\n" +
  "self.__PRECACHE = " +
  JSON.stringify(manifestEntries, null, 2) +
  ";\n";

if (check) {
  if (readFileSync(out, "utf8") !== body) {
    console.error("✗ precache-manifest.js is stale — run scripts/build-precache.mjs");
    process.exit(1);
  }
  console.log(`✓ precache-manifest.js is current (${manifestEntries.length} entries)`);
} else {
  writeFileSync(out, body);
  warnings.forEach((w) => console.warn("  warning:", w));
  console.log(`✓ precache-manifest.js — ${manifestEntries.length} entries`);
}
