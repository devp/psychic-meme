#!/usr/bin/env node
// Workbox spike: generate a precache manifest with content revisions.
//
// Deliberately NOT injectManifest, which rewrites sw.js itself and would put
// the service worker in the derived zone. This writes one data file that an
// authored sw.js importScripts(), so only the manifest is derived.
//
// Pass --check to verify the committed manifest is current instead of writing
// it. Without that, generation trades the hand-rolled version's tripwire for a
// file you can silently forget to regenerate.
//
//   node tools/build-precache.mjs variants/_spike-workbox [--check]

import { getManifest } from "workbox-build";
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const check = process.argv.includes("--check");
const variant = process.argv[2];
if (!variant) {
  console.error("usage: node tools/build-precache.mjs <variant-dir>");
  process.exit(2);
}

const root = new URL("..", import.meta.url).pathname;

const app = await getManifest({
  globDirectory: join(root, variant),
  globPatterns: ["**/*.{html,css,js,webmanifest,svg}"],
  globIgnores: ["sw.js", "precache-manifest.js", "**/*.d.ts"],
});

// The shared libs live outside the variant directory; glob them separately and
// rewrite the urls to the relative paths the page actually requests.
const libs = await getManifest({
  globDirectory: join(root, "lib"),
  globPatterns: ["*.js"],
});

const entries = [
  ...app.manifestEntries,
  ...libs.manifestEntries.map((/** @type {{url: string}} */ e) => ({ ...e, url: `../../lib/${e.url}` })),
];

const out = join(root, variant, "precache-manifest.js");
const body =
  "// GENERATED by tools/build-precache.mjs -- do not edit.\n" +
  "self.__PRECACHE = " +
  JSON.stringify(entries, null, 2) +
  ";\n";

if (check) {
  const current = readFileSync(out, "utf8");
  if (current !== body) {
    console.error(`✗ ${variant}/precache-manifest.js is stale — run without --check`);
    process.exit(1);
  }
  console.log(`✓ ${variant}/precache-manifest.js is current (${entries.length} entries)`);
} else {
  writeFileSync(out, body);
  [...app.warnings, ...libs.warnings].forEach((w) => console.warn("  warning:", w));
  console.log(`✓ ${variant}/precache-manifest.js — ${entries.length} entries`);
}
